-- Helper Function to check role
CREATE OR REPLACE FUNCTION auth.user_role() RETURNS user_role AS $$
  SELECT role FROM public.profiles WHERE id = auth.uid();
$$ LANGUAGE sql SECURITY DEFINER;

-- Profiles: Users can read their own, Managers can read all
CREATE POLICY "Users can view own profile" ON profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Managers can view all profiles" ON profiles FOR SELECT USING (auth.user_role() IN ('executive_manager', 'finance_admin'));
CREATE POLICY "Users can update own profile" ON profiles FOR UPDATE USING (auth.uid() = id);

-- Courses: Everyone can see published. Managers/Teachers can see all and insert/update.
CREATE POLICY "Anyone can view published courses" ON courses FOR SELECT USING (is_published = TRUE);
CREATE POLICY "Managers and Teachers can view all courses" ON courses FOR SELECT USING (auth.user_role() IN ('executive_manager', 'teacher'));
CREATE POLICY "Managers and Teachers can manage courses" ON courses FOR ALL USING (auth.user_role() IN ('executive_manager', 'teacher'));

-- Chapters & Lessons: Viewable if course is published OR user is manager/teacher. Manageable by manager/teacher.
CREATE POLICY "Public read chapters of published courses" ON chapters FOR SELECT USING (EXISTS (SELECT 1 FROM courses WHERE id = chapters.course_id AND is_published = TRUE));
CREATE POLICY "Manage chapters" ON chapters FOR ALL USING (auth.user_role() IN ('executive_manager', 'teacher'));

CREATE POLICY "Public read lessons of published courses" ON lessons FOR SELECT USING (EXISTS (SELECT 1 FROM chapters JOIN courses ON chapters.course_id = courses.id WHERE chapters.id = lessons.chapter_id AND courses.is_published = TRUE));
CREATE POLICY "Manage lessons" ON lessons FOR ALL USING (auth.user_role() IN ('executive_manager', 'teacher'));

-- Enrollments: View own. Managers see all. Manageable by managers.
CREATE POLICY "Users view own enrollments" ON enrollments FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Managers view all enrollments" ON enrollments FOR SELECT USING (auth.user_role() = 'executive_manager');
CREATE POLICY "Users can insert own enrollment (free courses / post payment)" ON enrollments FOR INSERT WITH CHECK (auth.uid() = user_id);

-- User Progress: View/Update own.
CREATE POLICY "Users manage own progress" ON user_progress FOR ALL USING (auth.uid() = user_id);

-- Quizzes: Read public. Manage managers/teachers.
CREATE POLICY "Read quizzes" ON quizzes FOR SELECT USING (TRUE);
CREATE POLICY "Manage quizzes" ON quizzes FOR ALL USING (auth.user_role() IN ('executive_manager', 'teacher'));
CREATE POLICY "Read questions" ON quiz_questions FOR SELECT USING (TRUE);
CREATE POLICY "Manage questions" ON quiz_questions FOR ALL USING (auth.user_role() IN ('executive_manager', 'teacher'));
CREATE POLICY "Read options" ON quiz_options FOR SELECT USING (TRUE);
CREATE POLICY "Manage options" ON quiz_options FOR ALL USING (auth.user_role() IN ('executive_manager', 'teacher'));

-- Quiz Results: View own. Insert own.
CREATE POLICY "Users view own quiz results" ON quiz_results FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Users insert own quiz results" ON quiz_results FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Managers view all quiz results" ON quiz_results FOR SELECT USING (auth.user_role() IN ('executive_manager', 'teacher'));

-- Wallets & Transactions: View own. Managers see all.
CREATE POLICY "Users view own wallet" ON wallets FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Finance admin views all wallets" ON wallets FOR SELECT USING (auth.user_role() = 'finance_admin');
CREATE POLICY "Users view own transactions" ON transactions FOR SELECT USING (EXISTS (SELECT 1 FROM wallets WHERE id = transactions.wallet_id AND wallets.id = auth.uid()));
CREATE POLICY "Finance admin views all transactions" ON transactions FOR SELECT USING (auth.user_role() = 'finance_admin');

-- Triggers (e.g. creating a wallet on profile creation)
CREATE OR REPLACE FUNCTION public.handle_new_user() 
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.wallets (id, balance) VALUES (new.id, 0);
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON public.profiles
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();
